#!/usr/bin/env python3
"""Generate the report's scaling figures and tables from analysed runs.

Input: one or more summary.json files written by analyze.py (each lists the
run directories it was built from). Output: LaTeX fragments (pgfplots
figures and tables) for main.tex to \\input; no number is typed by hand.

  report_figures.py SUMMARY.json [...] [--out DIR] [--allow-local]

By default the output goes to ../report/generated/ and every input must come
from artifacts/cluster/ (Vanda runs). Summaries built from local or simulated
runs are refused unless --allow-local is given together with an --out outside
report/generated/; such fragments carry a LOCAL PIPELINE TEST banner in
every caption. Each fragment starts with a comment naming its inputs.

Fragments (written only when the data exist):
Axes for time, problem size and core count are logarithmic (Lecture 12).
  fig_serial_n.tex                                   study "serial_n" (+ the strong serial row)
  fig_strong_runtime.tex, fig_strong_speedup.tex,
  fig_strong_efficiency.tex                          study "strong"
  tab_ranks_threads.tex                              study "ranks_threads" (+ strong rows at the same P)
  tab_schedule.tex                                   study "schedule"
  fig_weak_runtime.tex, fig_weak_efficiency.tex      study "weak" (per T; P0 = smallest P, stated)
  fig_phases.tex                                     strong-study hybrid rows, phase medians
  fig_comm_fraction.tex                              exchange time / wall time, strong and weak
  tab_accuracy_cost.tex                              studies "accuracy" (validate) and "theta"
  fig_gpu_runtime.tex, tab_gpu.tex                   study "gpu_timing" (device and cpu on the same workloads)
  tab_failed_runs.tex                                every failed, timed-out or skipped run
"""
import argparse
import itertools
import datetime
import json
import math
from pathlib import Path
import re
import sys

CODE = Path(__file__).resolve().parents[1]
REPORT_GEN = CODE.parent / "report/generated"


def esc(s):
    return str(s).replace("\\", "/").replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def has_study(row, study):
    return study in (row.get("studies") or "").split(",")


def load(paths):
    rows, failed, inputs = [], [], []
    for p in paths:
        d = json.loads(Path(p).read_text())
        rows += d["rows"]
        failed += d.get("failed", [])
        inputs += d.get("inputs", [str(Path(p).parent)])
    return rows, failed, inputs


class Writer:
    def __init__(self, out, inputs, local):
        self.out, self.inputs, self.local = out, inputs, local
        self.written = []

    def caption(self, text):
        banner = "\\textbf{LOCAL PIPELINE TEST, NOT A MEASUREMENT.} " if self.local else ""
        return banner + text

    def write(self, name, body):
        stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        head = (f"% Generated by code/scripts/report_figures.py at {stamp}; do not edit.\n"
                f"% Inputs: {', '.join(self.inputs)}\n")
        (self.out / name).write_text(head + body)
        self.written.append(name)


def label(r):
    return f"{r['ranks']}$\\times${r['threads']}"


# Distinct marks, so series stay apart in greyscale.
MARKS = ("*", "square*", "triangle*", "diamond*", "pentagon*")


def fig_xy(series, xlabel, ylabel, caption, lab, ideal=None, logx=True, logy=False, legend="north west",
           log_base_x=2, axis_opts=""):
    lines = ["\\begin{figure}[t]", "\\centering", "\\begin{tikzpicture}",
             "\\begin{axis}[width=0.9\\columnwidth, height=0.65\\columnwidth, "
             f"xlabel={{{xlabel}}}, ylabel={{{ylabel}}}, "
             + (f"xmode=log, log basis x={log_base_x}, " if logx else "")
             + ("ymode=log, " if logy else "")
             + axis_opts
             + f"legend pos={legend}, legend cell align=left, grid=major, grid style={{gray!25}}]"]
    for (name, pts), mark in zip(series, itertools.cycle(MARKS)):
        coords = " ".join(f"({x:g},{y:.4g})" for x, y in pts)
        lines.append(f"\\addplot+[mark={mark}, thick] coordinates {{{coords}}};")
        lines.append(f"\\addlegendentry{{{esc(name)}}}")
    if ideal:
        coords = " ".join(f"({x:g},{y:g})" for x, y in ideal)
        lines.append(f"\\addplot[black, dashed] coordinates {{{coords}}};")
        lines.append("\\addlegendentry{ideal}")
    lines += ["\\end{axis}", "\\end{tikzpicture}", f"\\caption{{{caption}}}", f"\\label{{{lab}}}",
              "\\end{figure}", ""]
    return "\n".join(lines)


def strong(rows, w):
    pts = [r for r in rows if has_study(r, "strong") and "speedup_vs_serial" in r]
    if not pts:
        return
    by_t = {}
    for r in pts:
        by_t.setdefault(r["threads"], []).append(r)
    series_t, series_s, series_e = [], [], []
    for t, rs in sorted(by_t.items()):
        rs.sort(key=lambda r: r["cores"])
        name = "MPI only ($T=1$)" if t == 1 else f"$T={t}$ threads per rank"
        series_t.append((name, [(r["cores"], r["wall_median_s"]) for r in rs]))
        series_s.append((name, [(r["cores"], r["speedup_vs_serial"]) for r in rs]))
        series_e.append((name, [(r["cores"], r["efficiency"]) for r in rs]))
    pmax = max(r["cores"] for r in pts)
    n = sorted({r["n"] for r in pts})
    base = (f"$N={','.join(map(str, n))}$, median of repetitions; serial Barnes--Hut baseline on the same "
            "CPU model and build.")
    w.write("fig_strong_runtime.tex", fig_xy(
        series_t, "allocated cores $P$", "timed-region wall time (s)", w.caption("Strong-scaling runtime. " + base),
        "fig:strong-runtime", logy=True, legend="north east"))
    w.write("fig_strong_speedup.tex", fig_xy(
        series_s, "allocated cores $P$", "speedup $S(P)$", w.caption("Strong-scaling speedup. " + base),
        "fig:strong-speedup", ideal=[(1, 1), (pmax, pmax)], logy=True))
    w.write("fig_strong_efficiency.tex", fig_xy(
        series_e, "allocated cores $P$", "efficiency $E(P)$", w.caption("Strong-scaling efficiency. " + base),
        "fig:strong-efficiency", ideal=[(1, 1), (pmax, 1)], legend="south west"))


def table(name, w, caption, lab, head, body, cols=None, wide=False, colsep=None):
    """Single-column tables are scaled to the column width; wide=True gives a
    full-width table* (cols then sets the column types, e.g. a p{} column).
    colsep narrows the gaps, in pt, when a wide table has many columns."""
    env = "table*" if wide else "table"
    cols = cols or "l" + "r" * (len(head) - 1)
    tab = (["\\begin{tabular}{" + cols + "}", "\\toprule", " & ".join(head) + " \\\\", "\\midrule"]
           + [" & ".join(row) + " \\\\" for row in body] + ["\\bottomrule", "\\end{tabular}"])
    if not wide:
        tab = ["\\resizebox{\\columnwidth}{!}{%"] + tab + ["}"]
    if colsep:
        tab = [f"\\setlength{{\\tabcolsep}}{{{colsep}pt}}"] + tab
    lines = [f"\\begin{{{env}}}[t]", "\\centering", "\\small", f"\\caption{{{caption}}}",
             f"\\label{{{lab}}}"] + tab + [f"\\end{{{env}}}", ""]
    w.write(name, "\n".join(lines))


def fmt_wall(r):
    return f"{r['wall_median_s']:.3f} [{r['wall_min_s']:.3f}, {r['wall_max_s']:.3f}]"


def ranks_threads(rows, w):
    rt = [r for r in rows if has_study(r, "ranks_threads")]
    if not rt:
        return
    ps = {r["cores"] for r in rt}
    rs = [r for r in rows if r["program"] == "bh_hybrid" and r["cores"] in ps
          and (has_study(r, "ranks_threads") or has_study(r, "strong"))
          and r["schedule"] == "dynamic"]
    rs.sort(key=lambda r: (r["cores"], -r["ranks"]))
    body = [[str(r["cores"]), label(r), fmt_wall(r),
             f"{r['speedup_vs_serial']:.2f}" if "speedup_vs_serial" in r else "--",
             f"{r['efficiency']:.2f}" if "efficiency" in r else "--",
             f"{r['traverse_imbalance']:.3f}" if "traverse_imbalance" in r else "--"] for r in rs]
    table("tab_ranks_threads.tex", w,
          w.caption("Ranks $\\times$ threads at fixed allocated cores $P$: timed-region wall time, median "
                    "[min, max] in seconds, speedup and efficiency against serial Barnes--Hut, and "
                    "traversal imbalance (max/mean over ranks)."),
          "tab:ranks-threads", ["$P$", "ranks$\\times$threads", "wall (s)", "$S$", "$E$", "imbalance"], body)


def schedule(rows, w):
    rs = [r for r in rows if has_study(r, "schedule") or
          (r["program"] == "bh_hybrid" and r["ranks"] * r["threads"] == r["cores"] and any(
              has_study(x, "schedule") and x["ranks"] == r["ranks"] and x["threads"] == r["threads"]
              and x["n"] == r["n"] for x in rows))]
    if not any(has_study(r, "schedule") for r in rs):
        return
    rs = sorted({id(r): r for r in rs}.values(), key=lambda r: (r["cores"], r["ranks"], r["schedule"], r["chunk"]))
    body = [[label(r), esc(r["schedule"]), str(r["chunk"]), fmt_wall(r),
             f"{r['traverse_imbalance']:.3f}" if "traverse_imbalance" in r else "--"] for r in rs]
    table("tab_schedule.tex", w,
          w.caption("OpenMP loop schedule and chunk size (chunk 0 = runtime default): timed-region wall "
                    "time, median [min, max] in seconds, and traversal imbalance."),
          "tab:schedule", ["ranks$\\times$threads", "schedule", "chunk", "wall (s)", "imbalance"], body)


def serial_n(rows, w):
    rs = [r for r in rows if r["program"] == "bh_serial"
          and (has_study(r, "serial_n") or has_study(r, "strong"))]
    if len({r["n"] for r in rs}) < 2:
        return
    if len({(r["theta"], r["leaf_size"], r["steps"], r["cpu_model"]) for r in rs}) > 1:
        sys.exit("serial_n: rows differ in theta, leaf size, steps or CPU model; split the input")
    rs.sort(key=lambda r: r["n"])
    xs = [math.log(r["n"]) for r in rs]
    ys = [math.log(r["wall_median_s"]) for r in rs]
    mx, my = sum(xs) / len(xs), sum(ys) / len(ys)
    slope = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
    r0 = rs[0]
    w.write("fig_serial_n.tex", fig_xy(
        [("serial Barnes--Hut", [(r["n"], r["wall_median_s"]) for r in rs])],
        "particles $N$", "timed-region wall time (s)",
        w.caption(f"Serial runtime against problem size, $\\theta={r0['theta']:g}$, leaf size {r0['leaf_size']}, "
                  f"{r0['steps']} timed steps, median of repetitions. Least-squares slope on the log--log axes: "
                  f"{slope:.3f}."), "fig:serial-n", logy=True))


def weak(rows, w):
    by_t = {}
    for r in rows:
        if has_study(r, "weak"):
            by_t.setdefault(r["threads"], []).append(r)
    by_t = {t: sorted(rs, key=lambda r: r["cores"]) for t, rs in by_t.items() if len(rs) >= 2}
    if not by_t:
        return
    name = lambda t: "MPI only ($T=1$)" if t == 1 else f"$T={t}$ threads per rank"
    runtime, eff, ends, notes = [], [], set(), []
    for t, rs in sorted(by_t.items()):
        p0 = rs[0]
        runtime.append((name(t), [(r["cores"], r["wall_median_s"]) for r in rs]))
        eff.append((name(t), [(r["cores"], p0["wall_median_s"] / r["wall_median_s"]) for r in rs]))
        ends |= {p0["cores"], rs[-1]["cores"]}
        per_core = sorted({r["n"] // r["cores"] for r in rs})
        notes.append(f"$T={t}$: $P_0={p0['cores']}$, $N_0={p0['n']}$, {', '.join(map(str, per_core))} particles per core")
    base = "; ".join(notes) + ". Constant particles per core is not constant work per core."
    w.write("fig_weak_runtime.tex", fig_xy(
        runtime, "allocated cores $P$", "timed-region wall time (s)",
        w.caption("Weak-scaling runtime. " + base), "fig:weak-runtime", logy=True))
    w.write("fig_weak_efficiency.tex", fig_xy(
        eff, "allocated cores $P$", "$T(P_0,N_0)/T(P,N)$", w.caption("Weak-scaling efficiency. " + base),
        "fig:weak", ideal=[(min(ends), 1), (max(ends), 1)], legend="south west"))


def phases(rows, w):
    rs = [r for r in rows if has_study(r, "strong") and r["program"] == "bh_hybrid"]
    if not rs:
        return
    t = min(r["threads"] for r in rs)
    rs = sorted((r for r in rs if r["threads"] == t), key=lambda r: r["cores"])
    names = [("integrate_median_s", "integrate"), ("exchange_median_s", "exchange"),
             ("build_median_s", "tree build"), ("traverse_median_s", "traversal")]
    # A phase measured as exactly zero (no exchange on one rank) cannot sit on a log axis.
    series = [(nm, [(r["cores"], r[key]) for r in rs if r[key] > 0]) for key, nm in names]
    w.write("fig_phases.tex", fig_xy(
        [s for s in series if s[1]], "allocated cores $P$", "median phase time (s)",
        w.caption(f"Phase times of the strong-scaling runs with $T={t}$. Each phase is the maximum over ranks, "
                  "so the phases need not sum to the wall time; zero values are omitted from the log axis."),
        "fig:phases", logy=True, legend="south west"))


def comm_fraction(rows, w):
    series = []
    for study in ("strong", "weak"):
        by_t = {}
        for r in rows:
            if has_study(r, study) and r["program"] == "bh_hybrid":
                by_t.setdefault(r["threads"], []).append(r)
        for t, rs in sorted(by_t.items()):
            rs.sort(key=lambda r: r["cores"])
            series.append((f"{study}, $T={t}$", [(r["cores"], r["exchange_median_s"] / r["wall_median_s"]) for r in rs]))
    if series:
        w.write("fig_comm_fraction.tex", fig_xy(
            series, "allocated cores $P$", "exchange time / wall time",
            w.caption("Share of the timed region spent in the per-step position exchange "
                      "(\\texttt{MPI\\_Allgatherv}), maximum over ranks divided by wall time."),
            "fig:comm-fraction"))


def accuracy(rows, inputs, w):
    acc = {}
    for d in inputs:
        for f in sorted(Path(d).glob("validate/*.txt")):
            for line in f.read_text().splitlines():
                m = re.search(r"validate n=(\d+) theta=([\d.]+) .*max_rel_err=(\S+) mean_rel_err=(\S+)", line)
                if m:
                    acc[float(m.group(2))] = (int(m.group(1)), m.group(3), m.group(4))
    cost = {r["theta"]: r for r in rows if r["program"] == "bh_hybrid"
            and (has_study(r, "theta") or has_study(r, "theta_cost"))}
    if not acc and not cost:
        return
    thetas = sorted(set(acc) | set(cost))
    body = []
    for th in thetas:
        a = acc.get(th)
        c = cost.get(th)
        body.append([f"{th:g}", f"{a[0]}" if a else "--", a[1] if a else "--", a[2] if a else "--",
                     label(c) if c else "--", fmt_wall(c) if c else "--"])
    table("tab_accuracy_cost.tex", w,
          w.caption("Accuracy against cost across $\\theta$: force error of serial Barnes--Hut against direct "
                    "summation (max and mean relative error at the stated $N$), and hybrid timed-region wall "
                    "time, median [min, max] in seconds."),
          "tab:accuracy-cost", ["$\\theta$", "$N$ (error)", "max rel.", "mean rel.", "config", "wall (s)"], body)


def fmt_n(n):
    """Particle count for a reader: 1000000 as 10^6, 3000000 as 3 x 10^6."""
    e = len(str(int(n))) - 1
    m = n / 10 ** e
    if m == 1:
        return f"$10^{{{e}}}$"
    return f"${m:g}\\times10^{{{e}}}$" if m == int(m) else f"{n:g}"


def gpu_timing(rows, w):
    rs = [r for r in rows if has_study(r, "gpu_timing") and r.get("backend") in ("device", "cpu")]
    paired = sorted((r for r in rs if "gpu_speedup_vs_cpu" in r), key=lambda r: r["n"])
    if not paired:
        return
    if len({(r["theta"], r["leaf_size"], r["steps"], r["threads"], r["cpu_model"], r.get("gpu_hardware")) for r in rs}) > 1:
        sys.exit("gpu_timing: rows differ in theta, leaf size, steps, threads, CPU or GPU; split the input")
    r0 = paired[0]
    gpu = (r0.get("gpu_hardware") or "GPU").split(",")[0]
    cpu_of = {r["n"]: r for r in rs if r["backend"] == "cpu"}
    what = (f"{r0['steps']} timed steps, $\\theta={r0['theta']:g}$, leaf size {r0['leaf_size']}, {esc(r0['cpu_model'])}. "
            f"Only the force traversal differs: on the device, or on {r0['threads']} bound CPU threads (schedule dynamic, "
            "chunk 64). Both backends build and flatten the tree and integrate on one host thread, and those times are "
            "included; setup and warmup are not.")
    w.write("fig_gpu_runtime.tex", fig_xy(
        [(f"device ({gpu})", [(r["n"], r["wall_median_s"]) for r in paired]),
         (f"cpu backend, {r0['threads']} cores", [(r["n"], cpu_of[r["n"]]["wall_median_s"]) for r in paired])],
        "particles $N$", "timed-region wall time (s)",
        w.caption(f"Wall time of the same program on the device and on {r0['threads']} CPU cores, median of repetitions. "
                  "Settings are in Table~\\ref{tab:gpu}."),
        "fig:gpu-runtime", logy=True, log_base_x=10, legend="south east",
        axis_opts="xtick={" + ",".join(f"{r['n']:g}" for r in paired) + "}, xticklabels={"
                  + ",".join("{" + fmt_n(r["n"]) + "}" for r in paired) + "}, "
                  "ytick={0.3,1,3,10,30}, log ticks with fixed point, "))
    body = [[fmt_n(r["n"]), fmt_wall(r), fmt_wall(cpu_of[r["n"]]), f"{r['gpu_speedup_vs_cpu']:.2f}",
             f"{r['traverse_median_s']:.3f}", f"{cpu_of[r['n']]['traverse_median_s']:.3f}",
             f"{r['flatten_median_s']:.3f}",
             f"{r['map_nodes_median_s'] + r['to_device_median_s'] + r['from_device_median_s']:.3f}",
             f"{r['reps']}/{r['cpu_reps']}"] for r in paired]
    table("tab_gpu.tex", w,
          w.caption("Device against CPU backend. Wall time is the median [min, max] in seconds. Below 1, cpu/device means "
                    "the device took longer. Kernel times are medians for each backend; flatten and map+transfer "
                    "(node mapping plus both transfers) are device-run medians, in seconds; reps is device/cpu. " + what),
          "tab:gpu", ["$N$", "device wall", "cpu wall", "cpu/device", "device kernel", "cpu kernel", "flatten",
                      "map+transfer", "reps"], body, wide=True, colsep=3.5)


def failed_runs(failed, w):
    body = [[esc(f["case"]), str(f["rep"]), esc(f.get("run", "")), esc("; ".join(f.get("problems") or []))]
            for f in sorted(failed, key=lambda f: (f.get("run", ""), f["case"], f["rep"]))]
    if not body:
        body = [["none", "", "", ""]]
    table("tab_failed_runs.tex", w,
          w.caption("Runs that failed, timed out or were skipped; they are kept in the records and excluded "
                    "from every median."),
          "tab:failed-runs", ["case", "rep", "run", "reason"], body,
          cols="lrlp{0.42\\textwidth}", wide=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("summaries", nargs="+")
    ap.add_argument("--out", default=str(REPORT_GEN))
    ap.add_argument("--allow-local", action="store_true")
    a = ap.parse_args()
    rows, failed, inputs = load(a.summaries)
    out = Path(a.out).resolve()
    non_cluster = [d for d in inputs if "artifacts/cluster/" not in str(Path(d).resolve()) + "/"]
    if non_cluster:
        if not a.allow_local:
            sys.exit(f"refusing: inputs not under artifacts/cluster/: {non_cluster} (use --allow-local and --out)")
        if out == REPORT_GEN.resolve():
            sys.exit("refusing to write local/simulated results into report/generated/")
    out.mkdir(parents=True, exist_ok=True)
    w = Writer(out, inputs, bool(non_cluster))
    serial_n(rows, w)
    strong(rows, w)
    ranks_threads(rows, w)
    schedule(rows, w)
    weak(rows, w)
    phases(rows, w)
    comm_fraction(rows, w)
    accuracy(rows, inputs, w)
    gpu_timing(rows, w)
    failed_runs(failed, w)
    print(f"wrote {len(w.written)} fragments to {out}: {', '.join(w.written)}"
          + (" [LOCAL PIPELINE TEST]" if w.local else ""))


if __name__ == "__main__":
    main()
