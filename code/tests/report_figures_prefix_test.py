#!/usr/bin/env python3
"""Regression check for report_figures.py --prefix (two jobs' results side by side).

From the bench1 summary (job 1528774): without --prefix the fragments equal the committed
ones in report/generated/ apart from the timestamp line; with --prefix b4 every file is
renamed b4_<name>, every \\label and \\ref to fig:/tab: becomes fig:b4-/tab:b4-, no
unprefixed label is left, and nothing else differs. Invalid prefixes are refused.

  python3 tests/report_figures_prefix_test.py      (from code/)
"""
from pathlib import Path
import re
import subprocess
import sys
import tempfile

CODE = Path(__file__).resolve().parent.parent
SUMMARY = CODE / "artifacts/cluster/analysis/bench1-1528774/summary.json"
CONTEXT = "Vanda job 1528774: all 64 cores of Gold 6438N node IN-008, 3 interleaved repetitions."
GEN = CODE.parent / "report/generated"
failed = 0


def expect(name, ok):
    global failed
    print(f"{'PASS' if ok else 'FAIL'} {name}")
    failed += not ok


def run(out, *extra):
    return subprocess.run([sys.executable, str(CODE / "scripts/report_figures.py"), str(SUMMARY), "--out", str(out),
                           "--context", CONTEXT, *extra], capture_output=True, text=True, cwd=CODE)


def body(path):
    return "".join(l for l in path.read_text().splitlines(True) if not l.startswith("% Generated by"))


with tempfile.TemporaryDirectory() as t:
    plain, pref = Path(t) / "plain", Path(t) / "pref"
    r1, r2 = run(plain), run(pref, "--prefix", "b4")
    expect("runs without and with --prefix", r1.returncode == 0 and r2.returncode == 0)
    names = sorted(p.name for p in plain.glob("*.tex"))
    expect(f"{len(names)} fragments written", len(names) >= 10)
    expect("prefixed names are b4_<name>", sorted(p.name for p in pref.glob("*.tex")) == [f"b4_{n}" for n in names])
    committed = [n for n in names if (GEN / n).exists()]
    expect("no prefix: identical to committed report/generated (timestamp aside)",
           committed and all(body(plain / n) == body(GEN / n) for n in committed))
    mapped = lambda s: re.sub(r"\\(label|ref)\{(fig|tab):", lambda m: f"\\{m.group(1)}{{{m.group(2)}:b4-", s)
    expect("prefix changes only labels and refs", all(body(pref / f"b4_{n}") == mapped(body(plain / n)) for n in names))
    allp = "".join(body(p) for p in pref.glob("*.tex"))
    expect("no unprefixed \\label or \\ref left", not re.search(r"\\(label|ref)\{(fig|tab):(?!b4-)", allp))
    expect("every fragment still has its label", all("\\label{" in body(p) for p in pref.glob("*.tex")))
    for bad in ("B4", "4b", "b-4", "b4 x"):
        r = run(Path(t) / "bad", "--prefix", bad)
        expect(f"prefix {bad!r} refused", r.returncode != 0 and not (Path(t) / "bad").exists())

print(f"report_figures_prefix_test: {failed} failed")
sys.exit(1 if failed else 0)
